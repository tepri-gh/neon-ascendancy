#!/usr/bin/env python3
"""Generate the world archive's ArchiveXL node deletions from data.

Some objects the owner's rules remove (stripped cars at a garage) are plain
world nodes with no variant to toggle. ArchiveXL can delete a node from a
streaming sector, but only by index, guarded by the sector's node count
(docs/research/quest-prop-cleanup.md section 3.4). Indexes change with game
patches, so the data names each node by a stable identity (its sector, its
global node id, type and template) and this tool resolves the index from a
fresh conversion of the sector:

  data/venues/world_deletions.json
    -> src/archive/pc/mod/neon_ascendancy_world.archive.xl (generated block)

It refuses a node whose type or template no longer matches, or whose node
is shared with another instance (deleting it would delete them all).
ArchiveXL itself refuses the whole sector patch if the node count or a
node's type differs at runtime, and logs it.

Usage:
  tools/world-deletions.py            regenerate the .xl block
  tools/world-deletions.py --check    fail if the block is out of date
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "venues" / "world_deletions.json"
XL = ROOT / "src" / "archive" / "pc" / "mod" / "neon_ascendancy_world.archive.xl"
CACHE = Path.home() / ".cache" / "neon-ascendancy"
DEFAULT_WK = CACHE / "wolvenkit-10.0.0-beta.1" / "WolvenKit.CLI"
DEFAULT_SECTORS = Path.home() / "na-prop-scratch" / "sectors"
BEGIN = "# BEGIN GENERATED by tools/world-deletions.py from data/venues/world_deletions.json. Do not edit."
END = "# END GENERATED world deletions"
CENSUS = Path.home() / "na-prop-scratch" / "census.jsonl"
CLASSIFICATION = ROOT / "data" / "venues" / "classification.json"


def convert(wk: Path, src: Path) -> dict:
    """The sector as WolvenKit JSON (converted in a temp folder, then dropped)."""
    work = CACHE / "world-deletions-work"
    work.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=work) as td:
        dst = Path(td) / src.name
        shutil.copy(src, dst)
        subprocess.run([str(wk), "convert", "serialize", td], check=True, stdin=subprocess.DEVNULL,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       env={**os.environ, "DOTNET_ROLL_FORWARD": "Major"})
        return json.loads(Path(str(dst) + ".json").read_text(encoding="utf-8"))["Data"]["RootChunk"]


def resolve(root: dict, d: dict) -> int:
    """The node index of d in its sector, after checking it is still the same node."""
    nodes = root["nodes"]
    data = root["nodeData"]["Data"]
    hits = [x for x in data if str(x["globalNodeId"]["hash"]) == str(d["global_node_id"])]
    if len(hits) != 1:
        sys.exit(f"{d['sector']}: global node {d['global_node_id']} found {len(hits)} times, expected once")
    idx = int(hits[0]["nodeIdx"])
    node = nodes[idx]["Data"]
    if node["$type"] != d["node_type"]:
        sys.exit(f"{d['sector']}: node {idx} is {node['$type']}, data says {d['node_type']}")
    tmpl = ((node.get("entityTemplate") or {}).get("DepotPath") or {}).get("$value", "")
    if d.get("template") and tmpl != d["template"]:
        sys.exit(f"{d['sector']}: node {idx} template is {tmpl!r}, data says {d['template']!r}")
    shared = [x for x in data if int(x["nodeIdx"]) == idx]
    if len(shared) != 1:
        sys.exit(f"{d['sector']}: node {idx} is shared by {len(shared)} instances; deleting it would remove all")
    return idx


def block(entries: list[dict], wk: Path, sectors: Path) -> str:
    by_sector: dict[str, list[dict]] = {}
    for d in entries:
        by_sector.setdefault(d["sector"], []).append(d)
    lines = [BEGIN, "streaming:", "  sectors:"]
    for sector, ds in sorted(by_sector.items()):
        root = convert(wk, sectors / sector)
        lines += [f"    - path: '{sector.replace('/', chr(92))}'",
                  f"      expectedNodes: {len(root['nodes'])}",
                  "      nodeDeletions:"]
        for d in sorted(ds, key=lambda d: resolve(root, d)):
            lines += [f"        # {d['venue']}: {d.get('debug_name') or d['global_node_id']} ({d['why'][:80]})",
                      f"        - index: {resolve(root, d)}",
                      f"          type: {d['node_type']}"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(xl: str, new: str) -> str:
    if BEGIN in xl:
        head, rest = xl.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        return head + new + tail
    return xl.rstrip("\n") + "\n" + new


def add_entries(entries: list[dict], ids: list[tuple[str, str, str]], strict: bool = True) -> None:
    """Append census nodes. Explicit ids are strict; a tour import skips what
    the census cannot delete (dynamic spawns such as community vehicles)."""
    present = {str(d["global_node_id"]) for d in entries}
    pending = {}
    for raw_id, venue, why in ids:
        node_id = str(raw_id).removesuffix("ULL")
        if node_id in present or node_id in pending:
            print(f"{node_id}: already present")
        else:
            pending[node_id] = (venue, why)
    if not pending:
        return
    found = {}
    with CENSUS.open(encoding="utf-8") as census:
        for line in census:
            row = json.loads(line)
            node_id = str(row["global_node_id"])
            if node_id in pending:
                if node_id in found:
                    sys.exit(f"{node_id}: found more than once in census")
                found[node_id] = row
    for node_id, (venue, why) in pending.items():
        row = found.get(node_id)
        problem = (f"not found in census {CENSUS} (a dynamic spawn?)" if row is None else
                   f"census node type is {row['node_type']}, expected worldEntityNode"
                   if row["node_type"] != "worldEntityNode" else None)
        if problem:
            if strict:
                sys.exit(f"{node_id}: {problem}")
            print(f"{node_id}: skipped, {problem}")
            continue
        entries.append({"sector": row["sector_path"].replace("\\", "/"), "global_node_id": node_id,
                        "node_type": row["node_type"], "template": row["entity_template"],
                        "debug_name": row["debug_name"], "pos": [row["x"], row["y"], row["z"]],
                        "venue": venue, "why": why})
        print(f"{node_id}: added for {venue}")


def tour_entries(path: Path) -> list[tuple[str, str, str]]:
    buckets = {x["id"]: x["bucket"] for x in json.loads(CLASSIFICATION.read_text(encoding="utf-8"))["items"]}
    ids = []
    with path.open(encoding="utf-8") as log:
        for line in log:
            row = json.loads(line)
            if row.get("event") != "stop":
                continue
            objects = [obj for obj in row.get("quest_objects", []) if obj.get("quest") is True]
            if not objects:
                continue
            venue = row.get("venue")
            if venue not in buckets:
                print(f"stop {row.get('code')}: venue {venue!r} has no classification, skipped")
                continue
            if buckets[venue] == "excluded":
                continue
            why = f"Quest-marked object at stop {row['code']}; venue-node-policy section 5 removes the object and marker."
            ids.extend((obj["id"], venue, why) for obj in objects)
    return ids


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the .xl block is out of date")
    ap.add_argument("--wolvenkit", type=Path, default=DEFAULT_WK)
    ap.add_argument("--sectors", type=Path, default=DEFAULT_SECTORS, help="raw sectors root (base/worlds/...)")
    sub = ap.add_subparsers(dest="command")
    add = sub.add_parser("add", help="add census nodes by entity id or from a tour")
    add.add_argument("ids", nargs="*", metavar="entity-id")
    add.add_argument("--venue", help="venue id for explicit entity ids")
    add.add_argument("--why", help="reason for explicit entity ids")
    add.add_argument("--from-tour", type=Path, help="import quest objects from tour.log")
    a = ap.parse_args()
    if a.command == "add" and ((a.ids and (not a.venue or not a.why)) or (not a.ids and not a.from_tour)):
        add.error("provide entity ids with --venue and --why, or --from-tour")
    data = json.loads(DATA.read_text(encoding="utf-8"))
    entries = data["nodes"]
    original_count = len(entries)
    if a.command == "add":
        add_entries(entries, [(node_id, a.venue, a.why) for node_id in a.ids])
        if a.from_tour:
            add_entries(entries, tour_entries(a.from_tour), strict=False)
    xl = XL.read_text(encoding="utf-8")
    new = splice(xl, block(entries, a.wolvenkit, a.sectors)) if entries else xl
    if a.check:
        if new != xl:
            print(f"{XL.relative_to(ROOT)} is out of date; run tools/world-deletions.py")
            return 1
        print(f"world deletions up to date ({len(entries)} nodes)")
        return 0
    if a.command == "add" and len(entries) != original_count:
        DATA.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    XL.write_text(new, encoding="utf-8")
    print(f"world deletions: {len(entries)} nodes -> {XL.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
